  await page.getByLabel("版本", { exact: true }).selectOption({ index: 1 });
  await expect(prompt).toHaveValue("前文\n" + requirement + "\n后文");
  await page.getByRole("button", { name: "查阅术语", exact: true }).click();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog", { name: "提示词术语助手" })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "查阅术语", exact: true })).toBeFocused();
