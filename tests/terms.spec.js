  await page.getByRole("button", { name: "查阅术语", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "提示词术语助手" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
